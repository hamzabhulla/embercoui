-- ─── Privilege-escalation guard (audit fix) ──────────────────────────────────
-- RLS restricts rows, not columns: without this guard any signed-up customer
-- could PATCH their own profile and set role='admin'. Column privilege revoke
-- plus a trigger (defense in depth). NOTE: the revoke applies to ALL
-- authenticated users (admins included), so role changes from the browser are
-- impossible by design — the admin panel changes roles through the backend's
-- service-role key, and the trigger's admin branch only ever fires for
-- service-role / direct-DB sessions. Service role is unaffected.
revoke update (role) on public.profiles from anon, authenticated;

create or replace function public.guard_profile_role()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.role is distinct from old.role then
    -- No JWT at all (direct DB / SQL Editor) or the service role (backend):
    -- already fully privileged channels, and the SQL Editor path is how the
    -- owner creates the FIRST admin. API callers always carry a JWT role.
    if coalesce(auth.role(), '') not in ('anon', 'authenticated') then
      return new;
    end if;
    if exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin') then
      return new;
    end if;
    raise exception 'Only an admin can change a profile role';
  end if;
  return new;
end $$;
drop trigger if exists profiles_guard_role on public.profiles;
create trigger profiles_guard_role before update on public.profiles
  for each row execute function public.guard_profile_role();

